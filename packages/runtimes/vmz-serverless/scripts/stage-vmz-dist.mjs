/**
 * Stage a VMZ server-host build into worker/vmz-dist and regenerate module registry.
 * Usage: node scripts/stage-vmz-dist.mjs <path-to-dist-profile-dir>
 * Example: node scripts/stage-vmz-dist.mjs ../../homepage/dist/web-ssr
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEST = path.join(ROOT, 'worker', 'vmz-dist');
const REGISTRY_OUT = path.join(ROOT, 'worker', 'module-registry.generated.ts');

const srcArg = process.argv[2] || process.env.VMZ_DIST;
if (!srcArg) {
    console.error('stage-vmz-dist: missing dist path (argv[2] or VMZ_DIST)');
    process.exit(1);
}

const SRC = path.resolve(srcArg);
if (!fs.existsSync(path.join(SRC, 'vmz-runtime.js'))) {
    console.error(`stage-vmz-dist: ${SRC} missing vmz-runtime.js — run vmz build with server-host profile first`);
    process.exit(1);
}
if (!fs.existsSync(path.join(SRC, 'vmz-routes.json'))) {
    console.error(`stage-vmz-dist: ${SRC} missing vmz-routes.json`);
    process.exit(1);
}

/** Skip static-only trees; keep server modules and runtime glue. */
function shouldCopy(relPosix) {
    if (relPosix.startsWith('assets/')) return false;
    if (relPosix.startsWith('vendor/vmz/test/')) return false;
    return true;
}

function rmDir(dir) {
    if (!fs.existsSync(dir)) return;
    fs.rmSync(dir, { recursive: true, force: true });
}

function copyTree(from, to, rel = '') {
    const entries = fs.readdirSync(from, { withFileTypes: true });
    for (const ent of entries) {
        const relChild = rel ? `${rel}/${ent.name}` : ent.name;
        const relPosix = relChild.replace(/\\/g, '/');
        if (!shouldCopy(relPosix)) continue;
        const srcPath = path.join(from, ent.name);
        const destPath = path.join(to, ent.name);
        if (ent.isDirectory()) {
            fs.mkdirSync(destPath, { recursive: true });
            copyTree(srcPath, destPath, relChild);
        } else if (ent.isFile()) {
            fs.mkdirSync(path.dirname(destPath), { recursive: true });
            fs.copyFileSync(srcPath, destPath);
        }
    }
}

function collectServerModules(dir, relPrefix, out) {
    if (!fs.existsSync(dir)) return;
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
        const rel = relPrefix ? `${relPrefix}/${ent.name}` : ent.name;
        const full = path.join(dir, ent.name);
        if (ent.isDirectory()) {
            collectServerModules(full, rel, out);
            continue;
        }
        if (!ent.name.endsWith('.js')) continue;
        const moduleId = `#server/${rel.replace(/\.js$/i, '').replace(/\\/g, '/')}`;
        const importPath = `./vmz-dist/#server/${rel.replace(/\\/g, '/')}`;
        out.set(moduleId, importPath);
    }
}

function collectAltServerModules(dir, out) {
    if (!fs.existsSync(dir)) return;
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, ent.name);
        if (ent.isDirectory()) {
            collectAltServerModules(full, out);
            continue;
        }
        if (!ent.name.endsWith('.js')) continue;
        const rel = path.relative(path.join(DEST, '_vmz_server'), full).replace(/\\/g, '/');
        const moduleId = `#server/${rel.replace(/\.js$/i, '')}`;
        const importPath = `./vmz-dist/_vmz_server/${rel}`;
        if (!out.has(moduleId)) out.set(moduleId, importPath);
    }
}

rmDir(DEST);
fs.mkdirSync(DEST, { recursive: true });
copyTree(SRC, DEST);

const modules = new Map();
collectServerModules(path.join(DEST, '#server'), '', modules);
collectAltServerModules(path.join(DEST, '_vmz_server'), modules);

const cases = [...modules.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
        ([id, importPath]) =>
            `        case ${JSON.stringify(id)}:\n            return new URL(${JSON.stringify(importPath)}, import.meta.url).href;`,
    )
    .join('\n');

const registrySource = `/** Generated by scripts/stage-vmz-dist.mjs — do not edit */
export function resolveServerModule(moduleId: string): string {
    switch (moduleId) {
${cases || '        default:\n            break;'}
        default:
            throw new Error(\`@vmz/serverless: unknown server module \${moduleId}\`);
    }
}
`;

fs.writeFileSync(REGISTRY_OUT, registrySource, 'utf8');
console.log(`stage-vmz-dist: ok (${modules.size} server modules) → ${DEST}`);
